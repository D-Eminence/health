/**
 * The design's workspace definitions (design/ehr-target src/catalog.ts): each workspace's fields, actions and statuses,
 * ported as data for the sample workspaces. Only definitions: no records, accounts or passwords, and nothing stored.
 */
type Kind = string;
export interface Field {
  key: string;
  label: string;
  type?:
    | "tel"
    | "text"
    | "number"
    | "date"
    | "datetime-local"
    | "textarea"
    | "email"
    | "checkbox"
    | "file";
  required?: boolean;
  options?: string[];
  suggestions?: string[];
  choices?: { value: string; label: string }[];
  multiple?: boolean;
  ref?: Kind;
}
export interface Action {
  id: string;
  label: string;
  from: string[];
  to: string;
  permission?: string;
  fields?: Field[];
}
export interface Module {
  id: string;
  title: string;
  group: string;
  kind: Kind;
  department?: string;
  fields: Field[];
  actions: Action[];
  initial?: string;
  patient?: boolean;
}
const f = (
  key: string,
  label: string,
  type: Field["type"] = "text",
  required = true,
): Field => ({ key, label, type, required });
const ref = (key: string, label: string, kind: Kind): Field => ({
  key,
  label,
  ref: kind,
  required: true,
});
const action = (
  id: string,
  label: string,
  from: string[],
  to: string,
  fields: Field[] = [],
  permission?: string,
): Action => ({ id, label, from, to, fields, permission });
